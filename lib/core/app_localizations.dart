  static String forLocale(Locale locale, String key) {
    final map = _values[locale.languageCode] ?? _values['ar']!;
    return map[key] ?? _values['ar']![key] ?? key;
  }

  static String of(BuildContext context, String key) {
    final settingsLocale = AppSettingsScope.of(context)?.locale;
    final locale =
        settingsLocale ??
        Localizations.maybeLocaleOf(context) ??
        WidgetsBinding.instance.platformDispatcher.locale;
    return forLocale(locale, key);
  }

  Future<AppStrings> load(Locale locale) async => AppStrings(locale);
}

class AppLocalizationsDelegate extends LocalizationsDelegate<AppStrings> {
  const AppLocalizationsDelegate();

  @override
  bool isSupported(Locale locale) => ['ar', 'en'].contains(locale.languageCode);

  @override
  Future<AppStrings> load(Locale locale) async => AppStrings(locale);

  @override
  bool shouldReload(covariant LocalizationsDelegate<AppStrings> old) => false;
}
